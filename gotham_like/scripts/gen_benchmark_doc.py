#!/usr/bin/env python3
"""Render docs/benchmarks/benchmark_*.json (+ EXPLAIN plans) into docs/BENCHMARKS.md."""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
B = ROOT / "docs" / "benchmarks"

LABELS = {
    "expand_1hop_typical": "Graph: 1-hop expansion (typical seed, fan-out 200)",
    "expand_2hop_typical": "Graph: 2-hop expansion (typical seed, fan-out 100, ≤2,000 nodes)",
    "expand_3hop_typical": "Graph: 3-hop expansion (typical seed, fan-out 50, ≤2,000 nodes)",
    "expand_2hop_hub_seed": "Graph: 2-hop expansion from a **hub** seed (capped)",
    "shortest_path_depth6": "Graph: shortest path, random pair, depth ≤ 6 (bidirectional)",
    "analytics_2hop_window": "Graph: analytics on a 2-hop window (degree, PageRank, components, betweenness)",
    "search_identifier": "Search: identifier lookup",
    "search_fuzzy": "Search: fuzzy trigram search",
    "timeline_entity": "Timeline: events of a hub entity (500 rows + histogram)",
    "timeline_global_week": "Timeline: all events in a 7-day window (hourly histogram)",
    "geo_radius_2km_time_window": "Geo: 2 km radius × 30-day window (entities + events)",
    "geo_knn_10": "Geo: 10 nearest neighbours (KNN)",
}


def table(res: dict) -> list[str]:
    q = res["queries_ms"]
    rows = ["| Operation | n | p50 ms | p95 ms | max ms |", "|---|---:|---:|---:|---:|"]
    rows += [f"| {LABELS.get(k, k)} | {v['n']} | {v['p50_ms']} | {v['p95_ms']} | {v['max_ms']} |" for k, v in q.items()]
    return rows


def main() -> None:
    files = sorted(B.glob("benchmark_*.json"), key=lambda p: json.loads(p.read_text())["scale"]["relationships"], reverse=True)
    L = ["# Performance benchmarks", "",
         "Generated by `scripts/benchmark.py` on SYNTHETIC / DEMONSTRATION DATA with a heavy-tailed degree distribution",
         "(1% of nodes receive ~25% of edge endpoints, so hubs with tens of thousands of edges exist). Timings measure the",
         "application code paths the API uses (SQLAlchemy + PostgreSQL 16/PostGIS 3.4, default server configuration), on the",
         "machine listed. No query cache is involved (Redis disabled for the run).", ""]
    for f in files:
        r = json.loads(f.read_text())
        s, ld = r["scale"], r["load"]
        L += [f"## {s['entities']:,} entities · {s['relationships']:,} relationships · {s['events']:,} events", "",
              f"Machine: {r['machine']['cpus']} vCPU, {r['machine']['postgres']}. Generated {r['generated_at'][:19]} UTC.", "",
              "| Load step | Rows | Seconds | Rows/s |", "|---|---:|---:|---:|"]
        for k in ("entities", "identifiers", "relationships", "events"):
            L.append(f"| {k} | {ld[k]['rows']:,} | {ld[k]['seconds']} | {ld[k]['rows_per_s']:,} |")
        L += [f"| rebuild {ld.get('indexes_rebuilt', '')} secondary indexes | | {ld.get('index_build_seconds', '')} | |",
              f"| VACUUM ANALYZE | | {ld['vacuum_analyze_s']} | |", "", f"Database size after load: **{ld['database_size']}**.", "", *table(r), ""]
    L += ["## Query plans (EXPLAIN ANALYZE, largest run)", "",
          "Captured by the benchmark into `docs/benchmarks/explain_*.txt`.", ""]
    for p in sorted(B.glob("explain_*.txt")):
        L += [f"### {p.stem.replace('explain_', '')}", "", "```", p.read_text().strip()[:4000], "```", ""]
    L += ["## Interpretation", "",
          "* Traversal cost is governed by the **frontier size × fan-out cap**, not by total graph size: each hop is one",
          "  index-range scan per frontier node on `(source_id, type, timestamp)` / `(target_id, type, timestamp)` partial indexes.",
          "* Hub seeds are the worst case; the per-node fan-out cap (`row_number() … <= fanout`) bounds the rows returned,",
          "  but PostgreSQL still reads the hub's index range to rank it — see *Performance bottlenecks* in VERIFICATION.md.",
          "* Graph analytics run in-process with NetworkX on the bounded window; exact betweenness is the most expensive step",
          "  and switches to sampling above 1,500 nodes.",
          "* The benchmark bulk-loads the way large initial loads should be done: secondary indexes are dropped, rows are COPYed,",
          "  and indexes are rebuilt with parallel maintenance workers. (Loading 10M edges with all indexes in place ran at",
          "  ~140k rows/min on default `shared_buffers`, i.e. roughly an order of magnitude slower.) Incremental ingestion through",
          "  the API pipeline keeps indexes online.",
          ""]
    (ROOT / "docs" / "BENCHMARKS.md").write_text("\n".join(L) + "\n")
    print("wrote docs/BENCHMARKS.md")


if __name__ == "__main__":
    main()
